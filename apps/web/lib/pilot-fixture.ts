function equalShares(amountCents: number, ids: string[]) {
  const share = Math.floor(amountCents / ids.length);
  return ids.map((personId, index) => ({
    personId,
    amountCents: share + (index < amountCents - share * ids.length ? 1 : 0),
  }));
}

