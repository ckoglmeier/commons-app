import test from 'node:test';
import assert from 'node:assert/strict';
import { BudgetCaptureSchema, captureInputs, budgetCaptureProperties } from './budget-capture';
import { startingBudgetInputs } from './budget-calculations';
import { budgetCaptureHandler } from './capture-route';
const payload = () => ({ id: '11111111-1111-4111-8111-111111111111', revision: 1, destination: 'savannah', lodgingEdited: false, inputs: captureInputs({ ...startingBudgetInputs('USD', 308), travelers: '4', nights: '3', optional: [{ id: 'PRIVATE', label: 'Sunset boat ride', perPerson: '10', participants: '2' }] }) });
test('budget capture retains every entered field, validates destination and recomputes totals', () => {
  const value = BudgetCaptureSchema.parse(payload());
  assert.ok(!JSON.stringify(value).includes('PRIVATE'));
  assert.equal(value.inputs.optional[0].label, 'Sunset boat ride');
  assert.equal(budgetCaptureProperties(value).totalMinor, 92400);
  assert.equal(BudgetCaptureSchema.safeParse({ ...payload(), destination: 'private-trip' }).success, false);
  assert.equal(BudgetCaptureSchema.safeParse({ ...payload(), email: 'private@example.com' }).success, false);
  const partial = BudgetCaptureSchema.parse({ ...payload(), inputs: { ...payload().inputs, travelers: 'not sure', nights: '' } });
  assert.equal(partial.inputs.travelers, 'not sure');
  assert.equal(budgetCaptureProperties(partial).estimateReady, false);
  assert.equal(budgetCaptureProperties(partial).totalMinor, null);
});
test('capture endpoint fails closed, respects privacy signals, validates input and does not block calculations', async () => {
  let saves = 0;
  const handler = budgetCaptureHandler({ enabled: () => true, save: async () => { saves++; return { saved: true, limited: false }; } });
  const request = (body: unknown, headers: Record<string,string> = {}) => new Request('https://www.commons.travel/api/v1/marketing/budget/', { method: 'POST', headers: { origin: 'https://www.commons.travel', ...headers }, body: JSON.stringify(body) });
  assert.equal((await handler(request(payload()))).status, 202);
  assert.equal((await handler(request(payload(), {origin:'https://other.invalid'}))).status, 403);
  assert.equal((await handler(request(payload(), {'sec-gpc':'1'}))).status, 204);
  assert.equal((await handler(request(payload(), {dnt:'1'}))).status, 204);
  assert.equal((await handler(request({ ...payload(), inputs: { text:'PRIVATE' } }))).status, 400);
  assert.equal((await handler(request({padding:'x'.repeat(18000)}))).status, 400);
  assert.equal(saves, 1);
  assert.equal((await budgetCaptureHandler({enabled:()=>false,save:async()=>{throw new Error('must not save');}})(request(payload()))).status,404);
  assert.equal((await budgetCaptureHandler({enabled:()=>true,save:async()=>{throw new Error('private DB error');}})(request(payload()))).status,503);
});
